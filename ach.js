/* PingPongLight achievements (docs/shop-spec.md "成就", docs/design/cosmetics-catalog.html section 12).
   ach-data.js (generated by tools/achdata.mjs) is the only list of achievements: this file draws whatever it holds, so a new or changed
   achievement needs no change here. Three sources of "earned":
     - the server decides most of them (from verified scores): /shop/state and /ach/sync answer with `ach` [{id,ts,l}], `pts`, `na`;
       /lb/submit answers with `ach` = the ones this run just earned (PPLA.fresh)
     - the ones marked chk 'l' are decided on this device (events sent by game.js and shop.js through PPLA.ev), kept in localStorage and
       sent up with /ach/sync {local:[ids]}
     - chk 'v' (duel results to be verified) and the ones the server cannot decide yet (na) show "即將開放" and are never granted here.
   Nothing here changes what is stored when the server cannot be reached: the cached server list is only replaced by a good answer. */
(function(){
'use strict';
const G=window.PPLG,C=window.PPLC,D=window.PPLACH;if(!G||!D||!Array.isArray(D.list))return;
const $=s=>document.querySelector(s),esc=G.esc,LS='ppl-ach-';
const BY={};for(const a of D.list)BY[a.id]=a;
const TN=['','銅','銀','金','傳說'];
const jget=(k,d)=>{try{const v=JSON.parse(G.lsGet(LS+k)||'null');return v==null?d:v}catch(e){return d}};
const jset=(k,v)=>G.lsSet(LS+k,JSON.stringify(v));

// ---------------------------------------------------------------- state
let LOC=jget('loc',{});                                   // decided on this device: {id: time}
let SRV=jget('srv',{});                                   // the last good server answer: {id: time}
let NAS=new Set(jget('na',[]));                           // ids the server cannot decide yet
let CMC=+G.lsGet(LS+'cmc')||0;                            // best combo (colours the default avatar)
const valid=o=>{const r={};if(o&&typeof o==='object')for(const k of Object.keys(o))if(BY[k])r[k]=+o[k]||1;return r};
LOC=valid(LOC);SRV=valid(SRV);
const earned=id=>!!(SRV[id]||LOC[id]);
const soon=a=>a.chk==='v'||!!a.na||NAS.has(a.id);         // not open yet
const open=a=>!soon(a);
function points(){let p=0;for(const a of D.list)if(earned(a.id))p+=a.pts;return p}

// ---------------------------------------------------------------- server data
function setServer(r){                                    // a good /shop/state or /ach/sync answer
  if(!r||!Array.isArray(r.ach))return;
  const o={};for(const x of r.ach){if(x&&typeof x.id==='string'&&BY[x.id])o[x.id]=+x.ts||1}
  SRV=o;jset('srv',SRV);
  if(Array.isArray(r.na)){NAS=new Set(r.na.filter(x=>typeof x==='string'));jset('na',[...NAS])}
  if(Number.isFinite(+r.cmc)){CMC=Math.max(0,+r.cmc);G.lsSet(LS+'cmc',String(CMC))}
  if(pageOn())render();
}
let upT=0,upBusy=false,upAgain=false,upRetry=0;
// local achievements go up with /ach/sync (debounced; a failure is retried at the next start or the next grant)
function flush(){clearTimeout(upT);upT=setTimeout(upload,1800)}
async function upload(){
  if(!G.ME)return;
  if(upBusy){upAgain=true;return}
  const ids=Object.keys(LOC);if(!ids.length)return;
  upBusy=true;
  try{
    const r=await G.api('/ach/sync',{local:ids.slice(0,200),pk:G.pkey()},8000);
    if(r&&r.ok&&Array.isArray(r.ach)){
      const before=new Set(Object.keys(SRV));setServer(r);
      if(window.PPLSHOP&&window.PPLSHOP.apply)window.PPLSHOP.apply(r);
      if(Array.isArray(r.fresh))for(const id of r.fresh)if(!before.has(id))note(id)
    }else if(r&&(r._s===429||r.error==='slow')){clearTimeout(upRetry);upRetry=setTimeout(upload,65000)}
  }finally{upBusy=false;if(upAgain){upAgain=false;flush()}}
}
// the earned list of a good server answer to something else (the shop screen's own sync): nothing to do, setServer did it

// ---------------------------------------------------------------- granting and notices
const NQ=[];                                              // notices waiting for a quiet moment
function grant(id){
  const a=BY[id];if(!a||a.chk!=='l'||earned(id)||soon(a))return false;
  LOC[id]=Date.now();jset('loc',LOC);note(id);flush();if(pageOn())render();return true}
function note(id){const a=BY[id];if(!a)return;NQ.push(id);if(!G.busy())showNotes()}
// the result screen asks for the waiting notices when it appears (and a notice also appears at once outside a run)
function showNotes(){
  const box=$('#achPop');if(!box)return;
  while(NQ.length&&box.children.length<3){
    const a=BY[NQ.shift()];if(!a)continue;
    const e=document.createElement('div');e.className='achNote';e.setAttribute('role','status');
    const rw=a.reward&&a.reward!=='成就點數'?'<span class="rw">'+esc(a.reward)+'</span>':'';
    e.innerHTML='<span class="tier t'+a.tier+'">'+TN[a.tier]+'</span><span class="tx"><b>成就達成　'+esc(a.name)+'</b><span class="d">'+esc(a.desc)+'</span>'+rw+'</span><span class="pt">+'+a.pts+'</span>';
    const rm=()=>{if(e.isConnected){e.remove();showNotes()}};
    e.onclick=rm;box.appendChild(e);setTimeout(rm,5200)}
}
function fresh(ids){                                      // /lb/submit: what this run earned on the server
  if(!Array.isArray(ids))return;let any=false;
  for(const id of ids)if(typeof id==='string'&&BY[id]&&!SRV[id]){SRV[id]=Date.now();any=true;note(id)}
  if(any){jset('srv',SRV);if(window.PPLSHOP)window.PPLSHOP.sync();if(pageOn())render()}
  showNotes()}

// ---------------------------------------------------------------- local achievements: events from the game and the shop
const eqNow=()=>C.state.eq;
const srcOf=id=>{for(const t of C.items)if(t.cat==='theme'&&(t.parts||[]).includes(id))return t.id;return id};   // the theme a part came from
function ev(n,d){
  d=d||{};
  try{
    if(n==='tut')grant('入門完成');
    else if(n==='cal')grant('精準調校');
    else if(n==='share')grant('分享喜悅');
    else if(n==='sky')grant('仰望');
    else if(n==='skyq'){const s=new Set(jget('skyq',[]));s.add(String(d.id));jset('skyq',[...s]);if(s.size>=5)grant('觀星')}
    else if(n==='set')grant('調音台');
    else if(n==='say')grant('打招呼');
    else if(n==='equip'){if(d.id&&C.byId[d.id]&&C.byId[d.id].how!=='default'||d.slot==='title'&&d.id){grant('換新裝');if(d.slot==='title'&&d.id)grant('署名')}}
    else if(n==='preview'){const s=new Set(jget('try',[]));if(d.id)s.add(d.id);jset('try',[...s]);if(s.size>=5)grant('試穿')}
    else if(n==='clear')clearEv(d);
  }catch(e){}
}
function clearEv(d){   // a normal single-player song was cleared: d = {key, last (ms of the previous clear of this song, 0 if never), paused, musicOff}
  const eq=eqNow(),parts=['orb','trail','hit','frame','bg'].map(s=>C.byId[eq[s]]).filter(Boolean);
  if(parts.some(p=>p.how.indexOf('ach:')===0)||(C.state.themeCol&&(C.byId[C.state.themeCol]||{}).how&&C.byId[C.state.themeCol].how.indexOf('ach:')===0))grant('戰利品');
  const three=['orb','trail','hit'].map(s=>C.byId[eq[s]]).filter(p=>p&&p.how!=='default');
  if(three.length===3&&new Set(three.map(p=>srcOf(p.id))).size===3)grant('混搭');
  if(d.last&&Date.now()-d.last>=30*864e5)grant('溫故');
  if(d.paused)grant('喘口氣');
  if(d.musicOff)grant('心中有歌');
}

// ---------------------------------------------------------------- the page
const UI={tab:-1,seen:new Set(jget('tabs',[]))};
const pageOn=()=>{const e=$('#ach');return !!e&&!e.classList.contains('hidden')};
function tabCounts(i){const l=D.list.filter(a=>i<0||a.cat===i);return[l.filter(a=>earned(a.id)).length,l.length]}
function titlesEarned(){const t=[];for(const a of D.list)if(earned(a.id))for(const id of a.rw||[])if(/^title\./.test(id)&&C.byId[id])t.push(id);return t}
function head(){
  const tot=D.list.filter(open),got=tot.filter(a=>earned(a.id)).length,pts=points(),all=D.list.filter(open).reduce((s,a)=>s+a.pts,0),pc=tot.length?Math.round(got/tot.length*100):0;
  const px=innerHeight<=480?56:96,me=G.ME,eq=C.state.eq,tt=titlesEarned();
  return '<div class="acAv">'+C.avHTML(C.avSpec(eq.avatar,C.tierOfCombo(CMC)),px)+'</div>'
    +'<div class="acMe"><div class="acNm">'+C.nameHTML(eq.plate,me?me.name:'（尚未設定暱稱）',eq.title)+'</div>'
    +'<div class="acPts"><b>'+pts.toLocaleString()+'</b> 成就點數<small>／ 目前可得 '+all.toLocaleString()+'</small></div>'
    +'<div class="acBar" role="progressbar" aria-valuemin="0" aria-valuemax="'+tot.length+'" aria-valuenow="'+got+'"><i style="width:'+pc+'%"></i></div>'
    +'<div class="acSub">已達成 '+got+' / '+tot.length+'（'+pc+'%）'+(tot.length<D.list.length?'　另有 '+(D.list.length-tot.length)+' 個即將開放':'')+'</div></div>'
    +'<div class="acTt"><div class="acTh">已取得的稱號 <small>'+tt.length+'</small></div>'+(tt.length?'<div class="acTl">'+tt.map(id=>C.titleHTML(id)).join('')+'</div>':'<div class="acNo">還沒有稱號。完成成就就會取得。</div>')+'</div>'}
function row(a){
  const e=earned(a.id),s=soon(a),ts=SRV[a.id]||LOC[a.id];
  const tag=s?'<span class="tt soon">即將開放</span>':a.chk==='l'?'<span class="tt loc">本機判定</span>':'';
  const date=e&&ts>1e11?'<small class="dt">'+new Date(ts).toLocaleDateString('zh-TW')+'</small>':'';
  return '<div class="acR'+(e?' got':'')+(s?' soon':'')+'"><span class="st" aria-label="'+(e?'已達成':s?'即將開放':'未達成')+'">'+(e?'✓':s?'…':'')+'</span>'
    +'<span class="nm"><span class="tier t'+a.tier+'">'+TN[a.tier]+'</span> <b>'+esc(a.name)+'</b> '+tag+date+'</span>'
    +'<span class="cd">'+esc(a.desc)+'</span><span class="rw">'+(a.lim?'<span class="lim">限定</span> ':'')+esc(a.reward)+'</span><span class="pt">'+a.pts+'</span></div>'}
function render(){
  if(!pageOn())return;
  $('#acHead').innerHTML=head();
  $('#acTabs').innerHTML=D.tabs.map((n,i)=>{const c=tabCounts(i);return '<button data-i="'+i+'" class="'+(UI.tab===i?'on':'')+'">'+esc(n)+'<small>'+c[0]+'/'+c[1]+'</small></button>'}).join('')
    +'<button data-i="-1" class="'+(UI.tab<0?'on':'')+'">全部<small>'+tabCounts(-1).join('/')+'</small></button>';
  let h='';
  if(UI.tab<0)D.tabs.forEach((n,i)=>{h+='<div class="acCat">'+esc(n)+'</div>'+D.list.filter(a=>a.cat===i).map(row).join('')});
  else h=D.list.filter(a=>a.cat===UI.tab).map(row).join('');
  $('#acList').innerHTML='<div class="acHd"><span></span><span>成就</span><span>條件</span><span>獎勵</span><span>點數</span></div>'+h;
}
function openPage(){
  G.initAudio();$('#home').classList.add('hidden');$('#ach').classList.remove('hidden');
  UI.tab=UI.tab>=-1&&UI.tab<D.tabs.length?UI.tab:-1;view(UI.tab);
  if(window.PPLSHOP)window.PPLSHOP.sync();
}
function view(i){
  UI.tab=i;if(i>=0){UI.seen.add(i);jset('tabs',[...UI.seen]);if(UI.seen.size>=D.tabs.length)grant('翻閱')}
  render();const l=$('#acList');if(l)l.scrollTop=0}
function closePage(){$('#ach').classList.add('hidden');G.showHome()}
$('#acTabs').addEventListener('click',e=>{const b=e.target.closest('button[data-i]');if(b)view(+b.dataset.i)});
$('#acBk').onclick=closePage;
$('#bAch').onclick=()=>openPage();
document.addEventListener('keydown',e=>{if(e.key==='Escape'&&pageOn())closePage()});
addEventListener('resize',()=>{if(pageOn())render()});

// boot: send up what this device decided earlier (silent when it cannot be reached)
if(G.ME&&Object.keys(LOC).length)setTimeout(upload,4000);
window.PPLA={ev,fresh,setServer,grant,flush:showNotes,open:openPage,render,earned,points,list:D.list,get loc(){return LOC},get srv(){return SRV}};
})();

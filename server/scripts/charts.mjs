// Builds src/charts.js: for every song and difficulty, how many beats the game asks for and how long the run lasts.
// The leaderboard uses it to check a submitted run. The beat-picking code is taken from game.js itself, so the
// two can never disagree. Run after any change to songs.js or the beat picking: `npm run charts`
// (`npm run charts -- --check` fails when src/charts.js is out of date; deploy runs it first).
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const SRV = join(dirname(fileURLToPath(import.meta.url)), '..'), ROOT = join(SRV, '..'), OUT = join(SRV, 'src', 'charts.js');
const game = readFileSync(join(ROOT, 'game.js'), 'utf8');
const cut = (from, to) => {
  const a = game.indexOf(from), b = game.indexOf(to, a);
  if (a < 0 || b < 0) throw new Error('game.js changed: cannot find "' + from + '" … "' + to + '"');
  return game.slice(a, b);
};
const box = { window: {} };
vm.runInNewContext(readFileSync(join(ROOT, 'songs.js'), 'utf8'), box);
const code = cut('function pickTargets(', 'const STARS=') + cut('const FILL_GAP=', 'function prepare(') + `
  const DIFFS=${cut('const DIFFS=', '\n').replace(/^const DIFFS=/, '').replace(/;\s*$/, '')};
  out={};
  for(const k of ORDER){const s=SD[k];if(!s)continue;
    const n=DIFFS.map(D=>{melList=[];bkList=[];for(const x of s.n)(x[3]===1?melList:bkList).push(x);lendTop();return pickTargets(melList,D.gap).length});
    out[k]={dur:s.dur,n,spd:DIFFS.map(D=>D.spd)}}`;
const ctx = { SD: box.window.SONGDATA, ORDER: box.window.SONGORDER || Object.keys(box.window.SONGDATA), melList: [], bkList: [], out: null };
vm.runInNewContext('let melList=[],bkList=[];' + code, ctx);
// songs of a reward constellation (a third element in SONGCONS): quick match never picks them, since most players have not found them yet
for (const [, keys, opt] of box.window.SONGCONS || []) if (opt && opt.rw != null) for (const k of keys) if (ctx.out[k]) ctx.out[k].rw = 1;
const text = '// Generated by scripts/charts.mjs from songs.js and game.js. Do not edit by hand.\n'
  + 'export const CHARTS = ' + JSON.stringify(ctx.out) + ';\n';
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('src/charts.js is out of date: run `npm run charts`'); process.exit(1); }
  console.log('charts up to date:', Object.keys(ctx.out).length, 'songs');
} else { writeFileSync(OUT, text); console.log('wrote', OUT, Object.keys(ctx.out).length, 'songs'); }

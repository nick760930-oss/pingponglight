// Builds src/catalog.js: every item the shop knows (id, category, whether other players see it, how it is obtained,
// store product id, theme parts, price in NT$). The source is cosmetics.js in the project root, the single list the
// game and the shop use: it is run in a sandbox (node:vm) and PPLC.items is read from it.
// Run after any change to the item list: `npm run catalog`. `npm run catalog -- --check` fails when src/catalog.js is out
// of date (deploy runs it first). `--src <file>` reads another file instead of ../cosmetics.js, `--out <file>` writes elsewhere (to compare).
//
// Item fields read from PPLC.items (an array of objects, or an object keyed by id):
//   id   "<category>.<key>", e.g. orb.star, theme.aurora, title.新星; also full, sponsor.30
//   cat  theme orb trail hit frame bg plate avatar emote share title full sponsor
//   vis  1 when other players can see it (avatar, plate, title)
//   how  default | buy | sponsor | ach:<achievement id>   (sponsor: given by sponsoring; the sponsor.* items are the purchasable packs)
//   pid  store product id (buy items and the sponsor.* packs), com.nocticat.pingponglight.<id>
//   parts  for themes: the item ids a theme purchase also gives
//   price  NT$ (sponsor: the amount)
//   also   optional, ach:<achievement id>: that achievement gives the item although it can be bought
//   limited  optional: only obtainable by achievement ("限定"; counts for 秘藏 and 萬象); stored as lim: 1
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const oi = process.argv.indexOf('--out');
const SRV = join(dirname(fileURLToPath(import.meta.url)), '..'), ROOT = join(SRV, '..'), OUT = oi > 0 ? resolve(process.argv[oi + 1]) : join(SRV, 'src', 'catalog.js');
const si = process.argv.indexOf('--src'), SRC = si > 0 ? resolve(process.argv[si + 1]) : join(ROOT, 'cosmetics.js');
const CATS = ['theme', 'orb', 'trail', 'hit', 'frame', 'bg', 'plate', 'avatar', 'emote', 'share', 'title', 'full', 'sponsor'];
const PID = 'com.nocticat.pingponglight.';
const die = m => { console.error('catalog: ' + m); process.exit(1); };

if (!existsSync(SRC)) die('cannot find ' + SRC);
const box = { window: {}, console };
box.globalThis = box;
try { vm.runInNewContext(readFileSync(SRC, 'utf8'), box, { filename: SRC, timeout: 5000 }); } catch (e) { die('cosmetics.js did not run in the sandbox: ' + e.message); }
const P = box.PPLC || (box.window && box.window.PPLC);
if (!P || !P.items) die('PPLC.items is missing');
const list = Array.isArray(P.items) ? P.items : Object.entries(P.items).map(([id, v]) => ({ id, ...v }));
const out = {};
for (const it of list) {
  const id = it && it.id;
  if (typeof id !== 'string' || !id) die('an item has no id');
  if (out[id]) die('duplicate id ' + id);
  const cat = it.cat;
  if (!CATS.includes(cat)) die(id + ': unknown category ' + cat);
  const how = String(it.how == null ? '' : it.how);
  if (!/^(default|buy|sponsor|ach:.+)$/.test(how)) die(id + ': bad how ' + how);
  const pid = how === 'buy' || cat === 'sponsor' ? String(it.pid || PID + id) : '';
  if (pid && pid !== PID + id) die(id + ': product id must be ' + PID + id + ' (got ' + pid + ')');
  const parts = Array.isArray(it.parts) ? it.parts.map(String) : [];
  const price = Number(it.price) || 0;
  if (!Number.isInteger(price) || price < 0) die(id + ': bad price');
  const also = it.also == null ? '' : String(it.also);   // a second way to get it: an achievement that gives it for free although it can also be bought
  if (also && !/^ach:.+/.test(also)) die(id + ': bad also ' + also);
  out[id] = { cat, vis: it.vis ? 1 : 0, how, pid, parts, price, ...(also ? { also } : {}), ...(it.limited ? { lim: 1 } : {}) };
}
for (const [id, v] of Object.entries(out)) for (const p of v.parts) if (!out[p]) die(id + ': part ' + p + ' is not an item');
const sorted = Object.fromEntries(Object.keys(out).sort().map(k => [k, out[k]]));
const text = '// Generated by scripts/catalog.mjs from cosmetics.js (PPLC.items). Do not edit by hand.\n'
  + 'export const CATALOG = {\n' + Object.entries(sorted).map(([k, v]) => ' ' + JSON.stringify(k) + ': ' + JSON.stringify(v)).join(',\n') + '\n};\n';
if (process.argv.includes('--check')) {
  if (!existsSync(OUT) || readFileSync(OUT, 'utf8') !== text) { console.error('src/catalog.js is out of date: run `npm run catalog`'); process.exit(1); }
  console.log('catalog up to date:', Object.keys(out).length, 'items');
} else { writeFileSync(OUT, text); console.log('wrote', OUT, Object.keys(out).length, 'items'); }
